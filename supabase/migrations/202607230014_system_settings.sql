ON TABLE app.system_settings
TO authenticated;

-- Configurações públicas podem ser lidas por visitantes.

CREATE POLICY system_settings_select_public
ON app.system_settings
FOR SELECT
TO anon
USING (
    is_public = true
);

-- Usuários autenticados também podem consultar configurações públicas.

CREATE POLICY system_settings_select_public_authenticated
ON app.system_settings
FOR SELECT
TO authenticated
USING (
    is_public = true
);

-- Administradores e usuários autorizados podem consultar todas.

CREATE POLICY system_settings_select_authorized
ON app.system_settings
FOR SELECT
TO authenticated
USING (
    app.is_admin()
    OR app.has_permission('core.settings.read')
    OR app.has_permission('core.settings.manage')
);

-- Criação exige permissão de gestão.

CREATE POLICY system_settings_insert_authorized
ON app.system_settings
FOR INSERT
TO authenticated
WITH CHECK (
    app.is_admin()
    OR app.has_permission('core.settings.manage')
);

-- Alteração exige permissão e respeita is_editable.

CREATE POLICY system_settings_update_authorized
ON app.system_settings
FOR UPDATE
TO authenticated
USING (
    (
        app.is_admin()
        OR app.has_permission('core.settings.manage')
    )
    AND is_editable = true
)
WITH CHECK (
    (
        app.is_admin()
        OR app.has_permission('core.settings.manage')
    )
    AND is_editable = true
);

-- Configurações estruturais não podem ser excluídas pela API comum.

CREATE POLICY system_settings_delete_authorized
ON app.system_settings
FOR DELETE
TO authenticated
USING (
    (
        app.is_admin()
        OR app.has_permission('core.settings.manage')
    )
    AND is_system = false
);

-- =============================================================================
-- FUNÇÃO PARA CONSULTAR CONFIGURAÇÕES
-- =============================================================================

CREATE OR REPLACE FUNCTION app.get_system_setting(
    p_key text,
    p_default jsonb DEFAULT NULL
)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, app
AS $$
    SELECT COALESCE(
        (
            SELECT setting.value
            FROM app.system_settings AS setting
            WHERE setting.key = p_key
              AND (
                  setting.is_public = true
                  OR app.is_admin()
                  OR app.has_permission('core.settings.read')
                  OR app.has_permission('core.settings.manage')
              )
            LIMIT 1
        ),
        p_default
    );
$$;

COMMENT ON FUNCTION app.get_system_setting(text, jsonb) IS
'Retorna uma configuração do sistema pelo identificador, respeitando autorização.';

GRANT EXECUTE
ON FUNCTION app.get_system_setting(text, jsonb)
TO anon, authenticated;

-- =============================================================================
-- PROTEÇÃO DE CONFIGURAÇÕES ESTRUTURAIS
-- =============================================================================

CREATE OR REPLACE FUNCTION app.prevent_protected_setting_changes()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, app
AS $$
BEGIN
    IF TG_OP = 'DELETE' AND OLD.is_system = true THEN
        RAISE EXCEPTION
            'A configuração estrutural "%" não pode ser excluída.',
            OLD.key;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        IF OLD.is_system = true AND NEW.key IS DISTINCT FROM OLD.key THEN
            RAISE EXCEPTION
                'O identificador da configuração estrutural "%" não pode ser alterado.',
                OLD.key;
        END IF;

        IF OLD.is_editable = false
           AND current_user NOT IN ('postgres', 'supabase_admin') THEN
            RAISE EXCEPTION
                'A configuração "%" não pode ser alterada diretamente.',
                OLD.key;
        END IF;
    END IF;

    RETURN CASE
        WHEN TG_OP = 'DELETE' THEN OLD
        ELSE NEW
    END;
END;
$$;

CREATE TRIGGER trg_protect_system_settings
BEFORE UPDATE OR DELETE ON app.system_settings
FOR EACH ROW
EXECUTE FUNCTION app.prevent_protected_setting_changes();

COMMIT;