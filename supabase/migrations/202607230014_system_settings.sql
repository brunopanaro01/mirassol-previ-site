-- =============================================================================
-- CONFIGURAÇÕES GERAIS DO SIGPREVI
-- =============================================================================
-- Armazena parâmetros globais da aplicação sem exigir alteração de código.
--
-- Exemplos:
-- - nome do sistema;
-- - nome da entidade;
-- - ambiente;
-- - manutenção;
-- - identidade institucional;
-- - parâmetros operacionais;
-- - configurações de módulos.
--
-- Valores sensíveis, como senhas, tokens, chaves privadas e credenciais,
-- não devem ser armazenados nesta tabela.
-- =============================================================================

CREATE TABLE app.system_settings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    key text NOT NULL,
    value jsonb NOT NULL DEFAULT '{}'::jsonb,

    category text NOT NULL DEFAULT 'general',
    description text,

    is_public boolean NOT NULL DEFAULT false,
    is_editable boolean NOT NULL DEFAULT true,
    is_system boolean NOT NULL DEFAULT false,

    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT system_settings_key_not_blank
        CHECK (length(trim(key)) > 0),

    CONSTRAINT system_settings_category_not_blank
        CHECK (length(trim(category)) > 0),

    CONSTRAINT system_settings_key_format
        CHECK (
            key ~ '^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)*$'
        ),

    CONSTRAINT system_settings_key_unique
        UNIQUE (key)
);

COMMENT ON TABLE app.system_settings IS
'Armazena configurações gerais, institucionais e operacionais do SIGPREVI.';

COMMENT ON COLUMN app.system_settings.key IS
'Identificador único da configuração no padrão categoria.chave.';

COMMENT ON COLUMN app.system_settings.value IS
'Valor da configuração armazenado em JSONB.';

COMMENT ON COLUMN app.system_settings.category IS
'Categoria lógica utilizada para organização e filtragem das configurações.';

COMMENT ON COLUMN app.system_settings.is_public IS
'Indica se a configuração pode ser consultada sem autenticação.';

COMMENT ON COLUMN app.system_settings.is_editable IS
'Indica se a configuração pode ser alterada pela interface administrativa.';

COMMENT ON COLUMN app.system_settings.is_system IS
'Indica configuração estrutural protegida contra exclusão comum.';

